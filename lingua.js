/* =========================================================
   FUNÇÕES AUXILIARES
   ========================================================= */
function escaparHTML(texto) {
  return String(texto ?? "")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");
}


/* =========================================================
   TABELAS AUTOMÁTICAS DE EXEMPLOS
   ========================================================= */

function linhaDeExemplo(linha) {

  const original = linha.trim();

  if (!original) return null;

  // Não transforma marcadores ou títulos
  if (/^[📌⚠️✅•]/u.test(original)) return null;

  if (
    /^━━━━━━━━/.test(original) ||
    /^\d+\./.test(original)
  ) {
    return null;
  }


  /* ---------------------------------------------------------
     FORMA + ELEMENTO → RESULTADO
     --------------------------------------------------------- */

  let m = original.match(
    /^(.+?)\s*\+\s*(.+?)\s*(?:→|=)\s*(.+)$/u
  );

  if (m) {

    const forma = m[1].trim();
    const elemento = m[2].trim();
    const resultado = m[3].trim();

    if (
      forma.length <= 60 &&
      elemento.length <= 40 &&
      resultado.length <= 120
    ) {
      return {
        tipo: "composicao",
        forma,
        elemento,
        resultado,
        sentido: ""
      };
    }
  }


  /* ---------------------------------------------------------
     FORMA → RESULTADO
     --------------------------------------------------------- */

  m = original.match(
    /^(.+?)\s*→\s*(.+)$/u
  );

  if (m) {

    const forma = m[1].trim();
    const resultado = m[2].trim();

    if (
      forma.length <= 60 &&
      resultado.length <= 120
    ) {
      return {
        tipo: "transformacao",
        forma,
        elemento: "",
        resultado,
        sentido: ""
      };
    }
  }


  /* ---------------------------------------------------------
     FORMA = RESULTADO
     --------------------------------------------------------- */

  m = original.match(
    /^(.+?)\s*=\s*(.+)$/u
  );

  if (m) {

    const forma = m[1].trim();
    const resultado = m[2].trim();

    if (
      forma.length <= 60 &&
      resultado.length <= 120
    ) {
      return {
        tipo: "transformacao",
        forma,
        elemento: "",
        resultado,
        sentido: ""
      };
    }
  }


  return null;
}


